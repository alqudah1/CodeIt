-- Class codes: a teacher's class and the children who joined it by code.
-- Mirrors CREATE_CLASSES in packages/codeit-backend/maintenanceSql.js.
-- Run once from the Supabase SQL editor (the app role cannot create tables).
create table if not exists public.classes (
  id         bigint generated by default as identity primary key,
  code       varchar(16) not null unique,
  name       varchar(80) not null,
  owner_id   integer not null references public.users(user_id) on delete cascade,
  created_at timestamptz not null default now()
);
create index if not exists idx_classes_owner on public.classes(owner_id);
alter table public.classes enable row level security;

create table if not exists public.class_members (
  id        bigint generated by default as identity primary key,
  class_id  bigint not null references public.classes(id) on delete cascade,
  user_id   integer not null references public.users(user_id) on delete cascade,
  joined_at timestamptz not null default now(),
  constraint uq_class_member unique (class_id, user_id)
);
create index if not exists idx_class_members_class on public.class_members(class_id);
alter table public.class_members enable row level security;
