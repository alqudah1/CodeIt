-- Data API access is denied by default. The trusted Vercel backend connects directly.
do $$
declare
  table_name text;
begin
  foreach table_name in array array[
    'users','students','lessons','puzzles','quiz_questions','student_lesson_progress',
    'student_puzzle_progress','student_quiz_attempt','parent_notification_log',
    'student_achievement','student_game_score','user_character','adult_email_verifications',
    'parent_child_links','legacy_parent_reviews','ai_projects','ai_project_likes',
    'ai_project_versions','ai_project_xp_awards','ai_usage_events','analytics_events',
    'founding_family_leads','parent_notification_preferences','student_milestones',
    'parent_notification_deliveries','password_reset_tokens','rewards','user_activity_daily'
  ]
  loop
    execute format('alter table public.%I enable row level security', table_name);
  end loop;
end;
$$;
