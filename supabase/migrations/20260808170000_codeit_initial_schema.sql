-- CodeIt production schema for Supabase PostgreSQL.
-- Tables intentionally use lower-case names so existing unquoted SQL remains compatible.

create or replace function public.set_updated_at()
returns trigger
language plpgsql
security invoker
set search_path = ''
as $$
begin
  new.updated_at = now();
  return new;
end;
$$;

create table public.users (
  user_id integer generated by default as identity primary key,
  username varchar(50) unique,
  name varchar(255) not null,
  email varchar(255) unique,
  password varchar(255) not null,
  role varchar(50) not null default 'student',
  dob date,
  parent_email varchar(255),
  created_at timestamptz default now(),
  total_xp integer default 0,
  weekly_xp integer default 0,
  level_id integer default 1,
  is_admin smallint not null default 0 check (is_admin in (0, 1))
);

create table public.students (
  student_id integer generated by default as identity primary key,
  user_id integer not null unique references public.users(user_id) on delete cascade,
  created_at timestamptz default now(),
  level_id integer default 1,
  total_xp integer default 0,
  weekly_xp integer default 0,
  current_streak integer not null default 0,
  longest_streak integer not null default 0,
  last_active_date date
);

create table public.lessons (
  id integer generated by default as identity primary key,
  title varchar(255) not null,
  description text not null,
  content text,
  example_code text,
